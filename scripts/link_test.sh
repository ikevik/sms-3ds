#!/usr/bin/env bash
# Stage 1 milestone: link libsms_game.a + libsms_platform.a + weak GX/GD placeholders against
# newlib/libctru into build/linktest.elf. Reports every symbol that is still unresolved.
# Needs build_game_lib.sh, prepare_pcport.sh + build_platform_lib.sh, undefined_symbols.sh first.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEVKITPRO="${DEVKITPRO:-/opt/devkitpro}"
DEVKITARM="${DEVKITARM:-$DEVKITPRO/devkitARM}"
CXX="$DEVKITARM/bin/arm-none-eabi-g++"; CC="$DEVKITARM/bin/arm-none-eabi-gcc"; SIZE="$DEVKITARM/bin/arm-none-eabi-size"
ARCH="-march=armv6k -mtune=mpcore -mfloat-abi=hard -mtp=soft"
B="$ROOT/build"; L="$B/linktest"; mkdir -p "$L"
for f in libsms_game.a libsms_platform.a undefined_symbols.txt; do [ -f "$B/$f" ] || { echo "missing build/$f"; exit 1; }; done

GXLIB=""; [ -f "$B/libsms_gx.a" ] && GXLIB="$B/libsms_gx.a" && echo "using real GX front half: build/libsms_gx.a"
# Placeholder GX/GD entry points: weak, so a real backend simply overrides them.
{
  echo '/* generated by scripts/link_test.sh: do-nothing GX/GD placeholders */'
  grep -E '^(GX|GD)[A-Za-z0-9_]*$' "$B/undefined_symbols.txt" | sort -u | \
    awk '{printf "__attribute__((weak)) int %s(void) { return 0; }\n", $1}'
} > "$L/gx_stubs.c"
echo "GX/GD placeholders: $(grep -c weak "$L/gx_stubs.c")"
non=$(grep -E '^(GX|GD)' "$B/undefined_symbols.txt" | grep -vE '^(GX|GD)[A-Za-z0-9_]*$' || true)
[ -n "$non" ] && echo "note: odd GX/GD names not stubbed: $non"

$CC $ARCH -O2 -w -c "$L/gx_stubs.c" -o "$L/gx_stubs.o" || exit 1
$CXX $ARCH -O2 -w -std=gnu++17 -D__3DS__ -I"$DEVKITPRO/libctru/include" -c "$ROOT/scripts/linktest/main.cpp" -o "$L/main.o" || exit 1

$CXX -specs=3dsx.specs $ARCH -Wl,--gc-sections -Wl,-Map,"$L/link.map" -o "$B/linktest.elf" \
  "$L/main.o" "$L/gx_stubs.o" \
  -Wl,--whole-archive "$B/libsms_game.a" "$B/libsms_platform.a" $GXLIB -Wl,--no-whole-archive \
  -L"$DEVKITPRO/libctru/lib" -L"$DEVKITPRO/portlibs/3ds/lib" -lcitro3d -lctru -lm \
  > "$L/link.log" 2>&1
rc=$?
grep -oE "undefined reference to \`[^']*'" "$L/link.log" | sed "s/undefined reference to \`//; s/'$//" | sort | uniq -c | sort -rn > "$B/link_undefined.txt"
grep -E "multiple definition" "$L/link.log" | sort -u > "$B/link_multiple.txt"
echo "link exit code: $rc"
echo "unresolved symbols: $(wc -l < "$B/link_undefined.txt" | tr -d ' ')   (build/link_undefined.txt)"
echo "multiple definitions: $(wc -l < "$B/link_multiple.txt" | tr -d ' ')   (build/link_multiple.txt)"
echo "other errors:"; grep -E "error|cannot|ld returned" "$L/link.log" | grep -vE "undefined reference|multiple definition" | sort -u | head -20
[ $rc -eq 0 ] && "$SIZE" "$B/linktest.elf"
exit $rc
